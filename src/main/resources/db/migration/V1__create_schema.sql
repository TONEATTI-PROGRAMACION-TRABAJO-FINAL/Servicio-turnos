-- Initial schema, written from the JPA entities. Hibernate only validates it (ddl-auto=validate).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id   VARCHAR(100) NOT NULL,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    first_name    VARCHAR(100) NOT NULL,
    last_name     VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_external_id UNIQUE (external_id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- active is TRUE while the process is active and NULL once it is final: the unique constraint treats NULLs as
-- distinct, so it allows any number of finished processes for the same user and slot but only one active one.
CREATE TABLE reservation_processes (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_external_id       VARCHAR(100) NOT NULL,
    professional_id        BIGINT NOT NULL,
    slot_date              DATE NOT NULL,
    start_time             TIME NOT NULL,
    status                 VARCHAR(20) NOT NULL,
    hold_id                VARCHAR(255),
    reservation_process_id VARCHAR(255),
    expires_at             TIMESTAMP(6) WITH TIME ZONE,
    failure_code           VARCHAR(100),
    request_event_id       VARCHAR(255),
    catedra_reservation_id BIGINT,
    phone_rejection_reason VARCHAR(100),
    cancellation_reason    VARCHAR(500),
    active                 BOOLEAN,
    created_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version                BIGINT,
    CONSTRAINT uk_reservation_processes_active_slot
        UNIQUE (user_external_id, professional_id, slot_date, start_time, active),
    CONSTRAINT uk_reservation_processes_hold_id UNIQUE (hold_id),
    CONSTRAINT uk_reservation_processes_reservation_process_id UNIQUE (reservation_process_id)
);

CREATE TABLE processed_appointment_actions (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id               VARCHAR(255) NOT NULL,
    event_type             VARCHAR(50) NOT NULL,
    reservation_process_id VARCHAR(255) NOT NULL,
    outcome                VARCHAR(20) NOT NULL,
    processed_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_processed_appointment_actions_event_id UNIQUE (event_id)
);
